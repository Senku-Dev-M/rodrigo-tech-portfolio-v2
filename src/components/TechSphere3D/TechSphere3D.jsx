// This sub-component renders a single technology sprite tag
function TechTagSprite({ name, category, position, index, total, hoverScale = 1.35 }) {
    const spriteRef = useRef(null);
    const [hovered, setHovered] = useState(false);
    
    // Generate a premium 2D canvas texture for the sprite
    const texture = useMemo(() => {
        const canvas = document.createElement('canvas');
        canvas.width = 300;
        canvas.height = 100;
        const ctx = canvas.getContext('2d');
        if (!ctx) return new THREE.Texture();

        const color = categoryColors[category] || '#00d4ff';
        
        // Draw glassy background pill
        ctx.fillStyle = 'rgba(10, 10, 10, 0.85)';
        ctx.strokeStyle = color;
        ctx.lineWidth = 4;
        
        // Rounded rectangle path
        const x = 10, y = 10, w = 280, h = 80, r = 40;
        ctx.beginPath();
        ctx.moveTo(x + r, y);
        ctx.lineTo(x + w - r, y);
        ctx.quadraticCurveTo(x + w, y, x + w, y + r);
        ctx.lineTo(x + w, y + h - r);
        ctx.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
        ctx.lineTo(x + r, y + h);
        ctx.quadraticCurveTo(x, y + h, x, y + h - r);
        ctx.lineTo(x, y + r);
        ctx.quadraticCurveTo(x, y, x + r, y);
        ctx.closePath();
        ctx.fill();
        ctx.stroke();

        // Check if we have SVG vector paths for this technology
        if (techPaths[name]) {
            ctx.save();
            // Position the SVG vector on the left of the pill
            ctx.translate(38, 30);
            ctx.scale(1.66, 1.66); // Scale standard 24x24 vector to target 40x40
            
            // Set dynamic glowing neons on the logo vector
            ctx.shadowColor = color;
            ctx.shadowBlur = 8;
            ctx.fillStyle = color;
            
            // Draw vector path using browser-native Path2D
            const p = new Path2D(techPaths[name]);
            ctx.fill(p);
            ctx.restore();
            
            // Draw text next to it
            ctx.font = 'bold 34px "Inter", "Outfit", sans-serif';
            ctx.fillStyle = '#ffffff';
            ctx.textAlign = 'left';
            ctx.textBaseline = 'middle';
            
            // Subtle text shadows for depth
            ctx.shadowColor = 'rgba(255, 255, 255, 0.2)';
            ctx.shadowBlur = 4;
            ctx.fillText(name, 96, 50);
        } else {
            // Fallback for plain text centering
            ctx.shadowColor = color;
            ctx.shadowBlur = 12;
            ctx.font = 'bold 36px "Inter", "Outfit", "Segoe UI", sans-serif';
            ctx.fillStyle = '#ffffff';
            ctx.textAlign = 'center';
            ctx.textBaseline = 'middle';
            ctx.fillText(name, 150, 50);
        }

        const tex = new THREE.CanvasTexture(canvas);
        tex.needsUpdate = true;
        return tex;
    }, [name, category]);

    // Animate sprite scale on hover
    useFrame(() => {
        if (!spriteRef.current) return;
        const targetScale = hovered ? hoverScale : 1.0;
        spriteRef.current.scale.lerp(new THREE.Vector3(targetScale * 3.2, targetScale * 1.08, 1), 0.15);
    });

    return (
        <sprite
            ref={spriteRef}
            position={position}
            onPointerOver={(e) => {
                e.stopPropagation();
                setHovered(true);
                document.body.style.cursor = 'pointer';
            }}
            onPointerOut={(e) => {
                setHovered(false);
                document.body.style.cursor = 'default';
            }}
        >
            <spriteMaterial 
                map={texture} 
                transparent={true} 
                depthWrite={false}
                toneMapped={false}
            />
        </sprite>
    );
}

// Renders the group of sprites arranged in spherical coordinates
function TechSphereGroup({ radius = 10, speed = 0.25 }) {
    const groupRef = useRef(null);
    const { pointer } = useThree();
    
    // Filter out only a solid subset of main skills to keep the sphere elegant
    const selectedSkills = useMemo(() => {
        // Filter some representative skills to avoid overcrowding the sphere (max 16)
        const filterList = [
            'Java', 'Spring Boot', 'C#', '.NET', 'Python', 'FastAPI', 
            'Node.js', 'TypeScript', 'React', 'Angular', 'PostgreSQL', 
            'MySQL', 'MongoDB', 'Docker', 'RabbitMQ', 'Git'
        ];
        return skills.filter(s => filterList.includes(s.name));
    }, []);

    // Calculate spherical coordinates for each tag
    const items = useMemo(() => {
        const count = selectedSkills.length;
        return selectedSkills.map((skill, idx) => {
            // Golden spiral algorithm to distribute points evenly on a sphere
            const phi = Math.acos(-1 + (2 * idx) / count);
            const theta = Math.sqrt(count * Math.PI) * phi;
            
            const x = radius * Math.sin(phi) * Math.cos(theta);
            const y = radius * Math.sin(phi) * Math.sin(theta);
            const z = radius * Math.cos(phi);
            
            return {
                ...skill,
                position: [x, y, z]
            };
        });
    }, [selectedSkills, radius]);

    // Slowly rotate the sphere and tilt based on mouse cursor position
    useFrame((state) => {
        if (!groupRef.current) return;
        const time = state.clock.getElapsedTime();
        
        // Base slow rotation
        groupRef.current.rotation.y = time * speed * 0.5;
        
        // Tilt sphere toward the user mouse pointer
        const targetX = pointer.y * 0.35;
        const targetY = pointer.x * 0.35;
        groupRef.current.rotation.x = THREE.MathUtils.lerp(groupRef.current.rotation.x, targetX, 0.05);
        groupRef.current.rotation.z = THREE.MathUtils.lerp(groupRef.current.rotation.z, -targetY, 0.05);
    });

    return (
        <group ref={groupRef}>
            {items.map((item, idx) => (
                <TechTagSprite
                    key={item.name}
                    name={item.name}
                    category={item.category}
                    position={item.position}
                    index={idx}
                    total={items.length}
                />
            ))}
            
            {/* Elegant futuristic wireframe sphere core */}
            <mesh>
                <sphereGeometry args={[radius * 0.85, 12, 12]} />
                <meshBasicMaterial 
                    color="#00d4ff" 
                    wireframe={true} 
                    transparent={true} 
                    opacity={0.03}
                />
            </mesh>
            
            {/* Glowing particle system in the center core */}
            <points>
                <sphereGeometry args={[radius * 0.4, 20, 20]} />
                <pointsMaterial 
                    color="#00d4ff" 
                    size={0.12} 
                    transparent={true} 
                    opacity={0.2}
                />
            </points>
        </group>
    );
}

